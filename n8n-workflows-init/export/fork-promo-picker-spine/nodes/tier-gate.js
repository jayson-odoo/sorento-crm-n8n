const j = $input.first().json;
const names = Array.isArray(j.name) ? j.name : [];
const parser = $("Call 'sub-query-reformulator'").first().json.output ?? {};

// stated tiers: tier tokens straight through; legacy compound names ("Sorento Dealer")
// tolerated via parseLevel so an old session or a stale parser cannot regress the gate.
const TIER_ORDER = ['dealer', 'office', 'end_user'];
const _statedSet = new Set();
for (const a of (Array.isArray(parser.access_levels) ? parser.access_levels : [])) {
  const s = String(a ?? '').trim().toLowerCase();
  if (TIER_ORDER.includes(s)) { _statedSet.add(s); continue; }
  const p = parseLevel(a);
  if (p) _statedSet.add(p.tier);
}
const tier_stated = TIER_ORDER.filter(t => _statedSet.has(t));

const entMap = mapEntitlement(names);

// brands the customer named THIS query. D9: the parser derives this now (statedBrands = brand
// entities ∪ the brand half of a COMPOUND stated level) because only the parser still has the
// RAW LLM levels — by the time they reach here they are tier tokens and the brand is gone.
// Fallback = the original entity-only scan, so an older/live parser degrades to yesterday's
// behaviour instead of throwing.
const query_brands = Array.isArray(parser.query_brands)
  ? parser.query_brands.filter(b => BRANDS.includes(String(b ?? '').toLowerCase()))
  : [...new Set((Array.isArray(parser.entities) ? parser.entities : [])
      .filter(e => String((e && e.hint) || '').toLowerCase() === 'brand')
      .map(e => BRANDS.find(v => String((e && (e.canonical_code || e.raw)) || '').toLowerCase().includes(v)))
      .filter(Boolean))];

// D11: a pick the parser ALREADY resolved outranks the ask. `_pending_pick` is the parser's own
// discriminator (roster context + "named no new scope"); the three flags beside it are
// spine-visible provenance, kept as defence in depth so a parser without `_pending_pick` still
// cannot have a customer's pick discarded (execs 12041783 / 12041879). The tier-pick answer turn
// is NOT a foreign pick — it states a tier and must proceed.
const pendingPick = parser._tier_pick_scope_reused !== true && (
  parser._pending_pick === true
  || parser._promo_pick_scope_reused === true
  || parser.dym_pick_applied === true
  || parser.member_pick_context === true);

// ── recomposition (plan §3) — the compound access_levels the CRM understands TODAY ──
// ⚠️ ORDER MATTERS, and it changed for F6: this block runs BEFORE the ask trigger, because a closed
// brand gate has to be able to CANCEL the ask. Nothing here reads tier_ask, so hoisting it leaves
// every recomposed value identical. On the ask turn tier_stated is empty, so `_chosen` is the whole
// entitled tier set — exactly the right probe for "does this contact hold the named brand at ANY
// tier", which is the question the ask must not be asked over.
const _chosen = tier_stated.length ? tier_stated : entMap.tiers;
let access_levels_recomposed, brand_gate_empty = false, brand_unheld = false;
if (_chosen.length === 0) {
  // entitlement holds no mappable tier (unknown names only): legacy full passthrough —
  // the mapper never guesses an unknown level, so the split model simply does not apply.
  access_levels_recomposed = names.slice().sort();
} else {
  const _r = recompose(_chosen, query_brands, names);
  brand_gate_empty = _r.brand_gate_empty;
  // F1: the NOTICE signal, separate from the SUPPRESSION signal. disallowed-entity-gate renders
  // from this one; only `brand_gate_empty` may suppress. Merging them told a brandless contact
  // "here's what you do have:" and then sent nothing (exec 12045520).
  brand_unheld = _r.brand_unheld;
  access_levels_recomposed = _r.access_levels;
  if (access_levels_recomposed.length === 0 && !brand_gate_empty && tier_stated.length) {
    // Q23: a stated tier the contact does not hold — answer at their REAL entitlement;
    // disallowed-entity-gate renders the notice that explains it. The brand gate does NOT
    // widen here: it sends []. ⚠️ Sending [] is a narrowing REQUEST, not the enforcement —
    // the first build claimed "[] makes the CRM return nothing" as fact and it was never
    // verified (UAC BLOCKER-2). D10 puts the actual denial in promo-picker, which suppresses
    // the answer and every attachment locally whatever the CRM returns.
    access_levels_recomposed = names.slice().sort();
  }
}

// D2 ask trigger. A zero-entitlement contact keeps the no-access lane: tier_proceed is
// false with names empty, and needsTierAsk's A5 bound means tier_ask stays false too.
// F6: `brandGateEmpty` makes the DENIAL outrank the ask. Asking "office / dealer / end user?" for a
// brand we are about to refuse both wastes the customer's turn and creates the pick turn on which
// the refusal was being lost (fork execs 12055170 → 12055181).
const tier_ask = needsTierAsk(parser.domain_hint, tier_stated, entMap.tiers, {
  pendingPick,
  brandGateEmpty: brand_gate_empty,
});
const tier_proceed = names.length > 0 && !tier_ask;

// D14: when we are about to ask, emit the per-tier probe plan. Each entry carries the compound
// names for ONE tier, from the same `recompose` the answer lane uses, so the availability probe
// asks exactly the question the customer's pick would ask. Empty off the ask lane, so every
// other turn is byte-inert.
const tier_probe_plan = tier_ask
  ? entMap.tiers.map(t => ({ tier: t, access_levels: recompose([t], query_brands, names).access_levels }))
  : [];

return {
  ...j,
  tier_stated,
  entitled_tiers: entMap.tiers,
  entitled_unknown: entMap.unknown,
  query_brands,
  pending_pick: pendingPick,
  tier_ask,
  tier_proceed,
  access_levels_recomposed,
  tier_probe_plan,
  brand_gate_empty,
  brand_unheld,
};
