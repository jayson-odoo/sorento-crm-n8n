// ── tier-gate ────────────────────────────────────────────────────────────────────────────
// access-tier-ask-plan.md §4 / D2. Sits between Aggregate and If4 on the promotion lane and
// decides whether the tier is RESOLVABLE — stated by the customer (the parser fork emits
// TIER TOKENS in access_levels), or the contact is entitled to exactly one tier. If4 reads
// `tier_proceed`; FALSE routes to access-level-choice-message (the tier ask, or the
// no-access message when name[] is empty).
//
// This node is ALSO the single place the tier×brand→compound recomposition happens
// (plan §3): `access_levels_recomposed` is what Call 'sub-get-results' sends to the CRM
// (semantic_input + user_prompt both read it), and disallowed-entity-gate's Q23 held-check
// reads `tier_stated` / `entitled_tiers` / `brand_gate_empty` / `brand_unheld` / `query_brands`.
//
// The block between the markers is a BYTE-COPY of tests/offline/access-tier/mapper.js
// (source of truth — 49/49 probe, 13/13 mutations; probe.js EB-* enforces byte identity).
// When the CRM ships additive brands[]/tiers[] on the entitlement read, this node consumes
// them instead and the mapper block is deleted (plan D8).
